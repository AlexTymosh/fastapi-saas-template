def get_privacy_column_policies_by_table() -> dict[str, dict[str, PrivacyColumnPolicy]]:
    grouped: dict[str, dict[str, PrivacyColumnPolicy]] = {}
    for policy in PRIVACY_COLUMN_POLICIES:
        table = grouped.setdefault(policy.table_name, {})
        if policy.column_name in table:
            raise ValueError(
                "Duplicate privacy column policy for "
                f"{policy.table_name}.{policy.column_name}"
            )
        table[policy.column_name] = policy
    return grouped


def get_privacy_column_policy(table_name: str, column_name: str) -> PrivacyColumnPolicy:
    return get_privacy_column_policies_by_table()[table_name][column_name]
