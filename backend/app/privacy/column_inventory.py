from __future__ import annotations

from dataclasses import dataclass

from app.privacy.data_inventory import (
    PrivacyFieldClassification,
    PrivacyFieldErasureAction,
)


@dataclass(frozen=True, slots=True)
class PrivacyColumnPolicy:
    """Column-level DSR handling contract for an inventoried table column."""

    table_name: str
    column_name: str
    classification: PrivacyFieldClassification
    export: bool
    erasure_action: PrivacyFieldErasureAction
    rationale: str


def _policy(
    table_name: str,
    column_name: str,
    classification: PrivacyFieldClassification,
    export: bool,
    erasure_action: PrivacyFieldErasureAction,
    rationale: str,
) -> PrivacyColumnPolicy:
    return PrivacyColumnPolicy(
        table_name=table_name,
        column_name=column_name,
        classification=classification,
        export=export,
        erasure_action=erasure_action,
        rationale=rationale,
    )


